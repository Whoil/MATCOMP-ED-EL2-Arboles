package ParteB;

public class Tripleta {
    private String s;
    private String p;
    private String o;



    public Tripleta(){

    }


    public Tripleta(String s, String p, String o){
        this.s=s;
        this.p=p;
        this.o=o;
    }



    public String getS(){
        return s;
    }

    public void setS(String s){
        this.s=s;
    }


    public String getP(){
        return p;
    }

    public void setP(String p){
        this.p=p;
    }


    public String getO(){
        return o;
    }



    public void setO(){
        this.o=o;
    }
}
